interface CountryCodes { a2: string; a3: string; num: string }

let byA2: Map<string, CountryCodes> | null = null;
let byA3: Map<string, CountryCodes> | null = null;
let byNum: Map<string, CountryCodes> | null = null;

function load() {
    if (byA2) return;
    byA2 = new Map();
    byA3 = new Map();
    byNum = new Map();
    for (let i = 0; i + 8 <= PACKED.length; i += 8) {
        const c = { a2: PACKED.slice(i, i + 2), a3: PACKED.slice(i + 2, i + 5), num: PACKED.slice(i + 5, i + 8) };
        byA2.set(c.a2, c);
        byA3.set(c.a3, c);
        byNum.set(c.num, c);
    }
}

/** 'US' -> 'usa' (Search Console filter value). */
export function alpha2ToGsc(a2: string): string | null {
    load();
    return byA2!.get(a2.toUpperCase())?.a3.toLowerCase() ?? null;
}

/** 'usa' -> 'US'. */
export function gscToAlpha2(a3: string): string | null {
    load();
    return byA3!.get(a3.toUpperCase())?.a2 ?? null;
}

/** world-atlas id ('840' or 840) -> 'US'. */
export function numericToAlpha2(num: string | number): string | null {
    load();
    const key = String(num).padStart(3, '0');
    return byNum!.get(key)?.a2 ?? null;
}

let displayNames: Intl.DisplayNames | null | undefined;

/** 'US' -> 'United States'. Falls back to the code. */
export function countryName(a2: string): string {
    if (!a2 || a2.length !== 2) return a2 || '(not set)';
    if (displayNames === undefined) {
        try {
            displayNames = new Intl.DisplayNames(['en'], { type: 'region' });
        } catch {
            displayNames = null;
        }
    }
    try {
        return displayNames?.of(a2.toUpperCase()) ?? a2;
    } catch {
        return a2;
    }
}
